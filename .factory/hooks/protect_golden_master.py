#!/usr/bin/env python3
"""PreToolUse hook: block any agent change to the golden master fixture.

Exit code 2 blocks the tool call and sends stderr back to Droid.
"""
import json
import re
import sys

PROTECTED = "golden_master.json"
CAPTURE_SCRIPT = "capture_golden_master"
READ_ONLY = re.compile(r"^\s*(cat|head|tail|less|wc|grep|rg|jq|git (diff|log|show|status)|python3? -m json\.tool)\b")
WRITE_TOKENS = re.compile(r"(>|\btee\b|\bsed\s+-i|\bmv\b|\bcp\b|\brm\b|\btruncate\b|write_text|open\()")

MESSAGE = (
    "Blocked by StayWell policy: tests/fixtures/golden_master.json is the extraction contract "
    "and cannot be modified or regenerated by an agent. If a case looks wrong, document it in "
    "docs/quirks.md and ask a human."
)


def main():
    try:
        event = json.load(sys.stdin)
    except ValueError:
        return 0
    tool = event.get("tool_name", "")
    tool_input = event.get("tool_input") or {}

    if tool in ("Create", "Edit", "ApplyPatch", "MultiEdit"):
        if PROTECTED in json.dumps(tool_input):
            print(MESSAGE, file=sys.stderr)
            return 2

    if tool == "Execute":
        command = str(tool_input.get("command", ""))
        if CAPTURE_SCRIPT in command:
            print(MESSAGE, file=sys.stderr)
            return 2
        if PROTECTED in command and (WRITE_TOKENS.search(command) or not READ_ONLY.match(command)):
            print(MESSAGE, file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
